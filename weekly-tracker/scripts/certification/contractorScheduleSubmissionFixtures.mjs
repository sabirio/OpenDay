// Contractor Schedule Submission / PM Review / Approved Baseline — LOCAL-ONLY
// deterministic E2E dataset (Simplification Phase 4B.2).
//
// A dedicated project, isolated from contractorScheduleFixtures.mjs's
// 960001/960002 (which 25 existing E2E tests in
// contractor-schedule-workspace.spec.js actively edit/save) — the
// submission lifecycle E2E spec drives this ONE project all the way from
// an empty Draft through Submit -> Request Changes -> resubmit -> Approve,
// a linear state machine that would corrupt those other tests' assumptions
// if it shared a project id. Same precedent as
// certifyScheduleLifecycleLockIntegrity.mjs's own dedicated 970001/970002.
//
// Run: node scripts/certification/contractorScheduleSubmissionFixtures.mjs
// (after: npm run cert:reset:contractor-schedule)

import { execFileSync } from 'node:child_process';

let SUPABASE_URL, ANON_KEY, DB_URL;
try {
  ({ SUPABASE_URL, ANON_KEY, DB_URL } = await import('./env.mjs'));
} catch (err) {
  console.error('BLOCKED: local Supabase target could not be proven.');
  console.error(`  ${err.message}`);
  process.exit(1);
}

try {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/`, { headers: { apikey: ANON_KEY } });
  if (!res.ok && res.status !== 404) throw new Error(`unexpected status ${res.status}`);
} catch (err) {
  console.error(`\nSKIPPED — ENVIRONMENT UNAVAILABLE: local Supabase stack is not reachable at ${SUPABASE_URL}.`);
  console.error('Run: npx supabase start (from weekly-tracker/), then npm run cert:reset:contractor-schedule first.');
  console.error(`(${err.message})\n`);
  process.exit(3);
}

// Fixed, non-colliding id — separate from fixtures.mjs (900001-900003),
// contractorWorkspaceFixtures.mjs (950001-950006), and
// contractorScheduleFixtures.mjs (960001-960002).
const PROJECT_ID = 960011; // SCHEDULE-SUBMIT

const CONTRACTOR_ASSIGNED_EMAIL = 'contractor-a-assigned@cert.local';
const PM_ASSIGNED_EMAIL = 'pm-a-assigned@cert.local';

function psql(sql) {
  return execFileSync('psql', [DB_URL, '-v', 'ON_ERROR_STOP=1', '-t', '-A', '-c', sql], {
    encoding: 'utf8',
    env: { ...process.env, PATH: `C:\\Program Files\\PostgreSQL\\100\\bin;${process.env.PATH}` },
  }).trim();
}

function main() {
  console.log('Contractor Schedule Submission local fixtures — target:', SUPABASE_URL, '(local only, guarded by env.mjs)');

  const contractorId = psql(`SELECT id FROM auth.users WHERE email = '${CONTRACTOR_ASSIGNED_EMAIL}';`);
  if (!contractorId) throw new Error(`Expected existing fixture user ${CONTRACTOR_ASSIGNED_EMAIL} not found — run "npm run cert:reset:contractor-schedule" first.`);
  const pmId = psql(`SELECT id FROM auth.users WHERE email = '${PM_ASSIGNED_EMAIL}';`);
  if (!pmId) throw new Error(`Expected existing fixture user ${PM_ASSIGNED_EMAIL} not found — run "npm run cert:reset:contractor-schedule" first.`);

  // Discard any prior submission history left by a previous run of this
  // fixture/spec (idempotent re-run support) before resetting the project —
  // same disable/enable-trigger bracket used by every other cert script
  // that needs to reset a project with schedule history; local-superuser-
  // only, never application-reachable.
  psql(`ALTER TABLE public.project_schedule_version_tasks DISABLE TRIGGER project_schedule_version_tasks_immutable;`);
  psql(`DELETE FROM public.project_schedule_versions WHERE project_id = ${PROJECT_ID};`);
  psql(`ALTER TABLE public.project_schedule_version_tasks ENABLE TRIGGER project_schedule_version_tasks_immutable;`);

  // Reset mode to AUTO_GENERATED + clear Scope in one statement (Scope
  // trigger reads NEW.schedule_ownership_mode; AUTO_GENERATED bypasses it
  // regardless of the Scope change in the same statement), then flip back
  // to CONTRACTOR_MANAGED in a separate statement that never touches scope.
  psql(`
    INSERT INTO public.projects (id, store_code, shopping_mall_name, company_id, project_status,
      construction_start_date, construction_end_date, target_opening_date, schedule_ownership_mode, scope)
    VALUES (${PROJECT_ID}, 'SCHEDULE-SUBMIT', 'Schedule Submission Test Mall', 'company-a', 'Active',
      CURRENT_DATE - 10, CURRENT_DATE + 90, CURRENT_DATE + 110, 'AUTO_GENERATED', NULL)
    ON CONFLICT (id) DO UPDATE SET schedule_ownership_mode = 'AUTO_GENERATED', scope = NULL;
    SELECT setval('public.projects_id_seq', 960100, false);
  `);
  psql(`UPDATE public.projects SET schedule_ownership_mode = 'CONTRACTOR_MANAGED' WHERE id = ${PROJECT_ID};`);
  console.log('  SCHEDULE-SUBMIT (CONTRACTOR_MANAGED) project upserted, reset to a fresh empty Draft');

  psql(`
    UPDATE public.profiles
    SET assigned_projects = (
      SELECT array_agg(DISTINCT x) FROM unnest(COALESCE(assigned_projects, '{}'::integer[]) || ARRAY[${PROJECT_ID}]::integer[]) AS x
    )
    WHERE id = '${contractorId}';
  `);
  console.log(`  ${CONTRACTOR_ASSIGNED_EMAIL} assigned_projects extended with ${PROJECT_ID} (additive)`);

  // PM does not need assigned_projects (can_write_project() is company-
  // scoped, not assigned_projects-scoped) — pm-a-assigned is already
  // company-a from base fixtures.mjs.

  psql(`DELETE FROM public.project_gantt_tasks WHERE project_id = ${PROJECT_ID};`);
  psql(`
    INSERT INTO public.project_gantt_tasks (project_id, wp_id, wp_label, phase_id, phase_label, is_archived, planned_start, planned_end, duration_days)
    VALUES
      (${PROJECT_ID}, 'demo.walls',     'Demo Walls',      'demolition', 'Demolition', false, NULL, NULL, NULL),
      (${PROJECT_ID}, 'finish.paint',   'Finish Paint',    'finishes',   'Finishes',   false, NULL, NULL, NULL),
      (${PROJECT_ID}, 'mep.electrical', 'MEP Electrical',  'mep',        'MEP',        false, NULL, NULL, NULL),
      (${PROJECT_ID}, 'legacy.archived','Legacy Archived', 'demolition', 'Demolition', true,  NULL, NULL, NULL);
  `);
  console.log('  SCHEDULE-SUBMIT scope seeded: 3 unscheduled active WPs + 1 archived (excluded from completeness/submission)');

  console.log('\nContractor Schedule Submission fixtures ready.');
  console.log(`  Assigned Contractor: ${CONTRACTOR_ASSIGNED_EMAIL}`);
  console.log(`  Assigned PM (company-scoped): ${PM_ASSIGNED_EMAIL}`);
  console.log(`  CONTRACTOR_MANAGED project: ${PROJECT_ID} (SCHEDULE-SUBMIT), fresh empty Draft`);
}

try {
  main();
  process.exit(0);
} catch (err) {
  console.error('CONTRACTOR SCHEDULE SUBMISSION FIXTURE SETUP FAILED:', err.message || err);
  process.exit(1);
}
