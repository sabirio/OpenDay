-- Phase B.7: canonical, versioned Project Execution Scope.
--
-- PM Project Scope remains high-level Discipline selection. This migration
-- derives an immutable Work Group snapshot for downstream Contractor Schedule
-- Setup without creating, editing, or archiving any Gantt activity. Existing
-- projects are intentionally not backfilled.

BEGIN;

CREATE TABLE IF NOT EXISTS public.project_execution_scope_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  ontology_version_id uuid NOT NULL REFERENCES public.work_ontology_versions(id) ON DELETE RESTRICT,
  schema_version integer NOT NULL DEFAULT 1 CHECK (schema_version = 1),
  revision_number integer NOT NULL CHECK (revision_number > 0),
  source_kind text NOT NULL CHECK (source_kind = 'PM_DISCIPLINE_SCOPE'),
  source_fingerprint text NOT NULL CHECK (btrim(source_fingerprint) <> ''),
  selected_discipline_ids uuid[] NOT NULL CHECK (cardinality(selected_discipline_ids) > 0),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, revision_number),
  UNIQUE (id, ontology_version_id)
);

CREATE INDEX IF NOT EXISTS project_execution_scope_versions_project_revision_idx
  ON public.project_execution_scope_versions(project_id, revision_number DESC);

-- Enables one foreign key to prove that each item Work Group belongs to its
-- stored Discipline and ontology version, rather than validating them as
-- three unrelated references.
CREATE UNIQUE INDEX IF NOT EXISTS work_ontology_work_groups_version_discipline_id_uniq
  ON public.work_ontology_work_groups(ontology_version_id, discipline_id, id);

CREATE TABLE IF NOT EXISTS public.project_execution_scope_items (
  execution_scope_version_id bigint NOT NULL,
  ontology_version_id uuid NOT NULL,
  discipline_id uuid NOT NULL,
  work_group_id uuid NOT NULL,
  PRIMARY KEY (execution_scope_version_id, work_group_id),
  FOREIGN KEY (execution_scope_version_id, ontology_version_id)
    REFERENCES public.project_execution_scope_versions(id, ontology_version_id)
    ON DELETE CASCADE,
  FOREIGN KEY (ontology_version_id, discipline_id, work_group_id)
    REFERENCES public.work_ontology_work_groups(ontology_version_id, discipline_id, id)
    ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS project_execution_scope_items_version_idx
  ON public.project_execution_scope_items(execution_scope_version_id);
CREATE INDEX IF NOT EXISTS project_execution_scope_items_work_group_idx
  ON public.project_execution_scope_items(ontology_version_id, work_group_id);

CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION private.prevent_execution_scope_snapshot_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog
AS $$
BEGIN
  RAISE EXCEPTION 'EXECUTION_SCOPE_SNAPSHOT_IMMUTABLE' USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS project_execution_scope_versions_immutable
  ON public.project_execution_scope_versions;
CREATE TRIGGER project_execution_scope_versions_immutable
  BEFORE UPDATE ON public.project_execution_scope_versions
  FOR EACH ROW EXECUTE FUNCTION private.prevent_execution_scope_snapshot_update();

DROP TRIGGER IF EXISTS project_execution_scope_items_immutable
  ON public.project_execution_scope_items;
CREATE TRIGGER project_execution_scope_items_immutable
  BEFORE UPDATE ON public.project_execution_scope_items
  FOR EACH ROW EXECUTE FUNCTION private.prevent_execution_scope_snapshot_update();

CREATE OR REPLACE FUNCTION private.sync_project_execution_scope_from_disciplines()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, private, pg_temp
AS $$
DECLARE
  selected_discipline_ids uuid[];
  source_fingerprint text;
  latest_fingerprint text;
  next_revision integer;
  v_execution_scope_version_id bigint;
  inserted_item_count integer;
BEGIN
  -- Compatibility boundary: legacy projects stay outside the new model until
  -- they are explicitly migrated through a future product workflow.
  IF NEW.work_ontology_version_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT array_agg(discipline.id ORDER BY discipline.display_order, discipline.id)
    INTO selected_discipline_ids
  FROM public.work_ontology_disciplines discipline
  WHERE discipline.ontology_version_id = NEW.work_ontology_version_id
    AND discipline.id IN (
      SELECT value::uuid
      FROM jsonb_array_elements_text(NEW.scope->'disciplineIds')
    );

  IF selected_discipline_ids IS NULL OR cardinality(selected_discipline_ids) = 0 THEN
    RAISE EXCEPTION 'INVALID_EXECUTION_SCOPE: no valid PM Disciplines'
      USING ERRCODE = '22023';
  END IF;

  source_fingerprint := NEW.work_ontology_version_id::text || ':'
    || array_to_string(selected_discipline_ids, ',');

  SELECT version.source_fingerprint
    INTO latest_fingerprint
  FROM public.project_execution_scope_versions version
  WHERE version.project_id = NEW.id
  ORDER BY version.revision_number DESC
  LIMIT 1;

  IF latest_fingerprint IS NOT DISTINCT FROM source_fingerprint THEN
    RETURN NEW;
  END IF;

  SELECT COALESCE(max(version.revision_number), 0) + 1
    INTO next_revision
  FROM public.project_execution_scope_versions version
  WHERE version.project_id = NEW.id;

  INSERT INTO public.project_execution_scope_versions (
    project_id,
    ontology_version_id,
    revision_number,
    source_kind,
    source_fingerprint,
    selected_discipline_ids,
    created_by
  ) VALUES (
    NEW.id,
    NEW.work_ontology_version_id,
    next_revision,
    'PM_DISCIPLINE_SCOPE',
    source_fingerprint,
    selected_discipline_ids,
    auth.uid()
  )
  RETURNING id INTO v_execution_scope_version_id;

  INSERT INTO public.project_execution_scope_items (
    execution_scope_version_id,
    ontology_version_id,
    discipline_id,
    work_group_id
  )
  SELECT
    v_execution_scope_version_id,
    work_group.ontology_version_id,
    work_group.discipline_id,
    work_group.id
  FROM public.work_ontology_work_groups work_group
  WHERE work_group.ontology_version_id = NEW.work_ontology_version_id
    AND work_group.discipline_id = ANY(selected_discipline_ids)
  ORDER BY work_group.display_order, work_group.id;

  GET DIAGNOSTICS inserted_item_count = ROW_COUNT;
  IF inserted_item_count = 0 THEN
    RAISE EXCEPTION 'INVALID_EXECUTION_SCOPE: selected Disciplines have no Work Groups'
      USING ERRCODE = '22023';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS projects_sync_execution_scope
  ON public.projects;
CREATE TRIGGER projects_sync_execution_scope
  AFTER INSERT OR UPDATE OF scope, work_ontology_version_id ON public.projects
  FOR EACH ROW EXECUTE FUNCTION private.sync_project_execution_scope_from_disciplines();

ALTER TABLE public.project_execution_scope_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.project_execution_scope_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS project_execution_scope_versions_select
  ON public.project_execution_scope_versions;
CREATE POLICY project_execution_scope_versions_select
  ON public.project_execution_scope_versions
  FOR SELECT TO authenticated
  USING (public.can_access_project(project_id));

DROP POLICY IF EXISTS project_execution_scope_items_select
  ON public.project_execution_scope_items;
CREATE POLICY project_execution_scope_items_select
  ON public.project_execution_scope_items
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.project_execution_scope_versions version
      WHERE version.id = project_execution_scope_items.execution_scope_version_id
        AND public.can_access_project(version.project_id)
    )
  );

REVOKE ALL ON TABLE public.project_execution_scope_versions
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON TABLE public.project_execution_scope_items
  FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.project_execution_scope_versions TO authenticated;
GRANT SELECT ON TABLE public.project_execution_scope_items TO authenticated;
REVOKE ALL ON SEQUENCE public.project_execution_scope_versions_id_seq
  FROM PUBLIC, anon, authenticated, service_role;

REVOKE ALL ON FUNCTION private.prevent_execution_scope_snapshot_update()
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION private.sync_project_execution_scope_from_disciplines()
  FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
