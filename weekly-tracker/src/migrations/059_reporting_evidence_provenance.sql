-- R1.1 Reporting evidence/provenance foundation. Additive only: historic rows
-- remain NULL and are interpreted in core as LEGACY_UNSPECIFIED. No report,
-- progress, schedule, Risk, or Site Visit calculation is rewritten.

BEGIN;

CREATE TABLE IF NOT EXISTS public.contractor_report_scope_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  template_id uuid,
  template_version integer,
  schema_version integer,
  selected_wp_ids jsonb NOT NULL,
  scope_fingerprint text NOT NULL,
  report_period_start date NOT NULL,
  report_period_end date NOT NULL,
  -- Nullable provenance only. R1.1 must also run on local/schema-v1
  -- environments that deliberately do not install the optional 049 schedule
  -- lifecycle extension; R1.2 will populate it only when provenance is safe.
  schedule_version_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (jsonb_typeof(selected_wp_ids) = 'array'),
  CHECK (report_period_start <= report_period_end)
);

CREATE INDEX IF NOT EXISTS contractor_report_scope_snapshots_project_idx
  ON public.contractor_report_scope_snapshots(project_id, created_at DESC);

ALTER TABLE public.contractor_reports
  ADD COLUMN IF NOT EXISTS scope_snapshot_id bigint REFERENCES public.contractor_report_scope_snapshots(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX IF NOT EXISTS contractor_reports_scope_snapshot_unique
  ON public.contractor_reports(scope_snapshot_id) WHERE scope_snapshot_id IS NOT NULL;

ALTER TABLE public.contractor_report_wps
  ADD COLUMN IF NOT EXISTS report_item_state text,
  ADD COLUMN IF NOT EXISTS source_report_wp_id bigint REFERENCES public.contractor_report_wps(id) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS confirmation_mode text,
  ADD COLUMN IF NOT EXISTS batch_confirmation_id uuid;

ALTER TABLE public.contractor_report_wps
  DROP CONSTRAINT IF EXISTS contractor_report_wps_report_item_state_check,
  ADD CONSTRAINT contractor_report_wps_report_item_state_check
    CHECK (report_item_state IS NULL OR report_item_state IN ('UPDATED','CONFIRMED_UNCHANGED','CARRIED_UNREVIEWED','NOT_IN_REPORTING_SCOPE','LEGACY_UNSPECIFIED')),
  DROP CONSTRAINT IF EXISTS contractor_report_wps_confirmation_mode_check,
  ADD CONSTRAINT contractor_report_wps_confirmation_mode_check
    CHECK (confirmation_mode IS NULL OR confirmation_mode IN ('INDIVIDUAL','BATCH')),
  DROP CONSTRAINT IF EXISTS contractor_report_wps_confirmation_metadata_check,
  ADD CONSTRAINT contractor_report_wps_confirmation_metadata_check
    CHECK ((confirmation_mode IS NULL AND batch_confirmation_id IS NULL) OR report_item_state = 'CONFIRMED_UNCHANGED');

CREATE OR REPLACE FUNCTION public.capture_contractor_report_scope_snapshot()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_template_id uuid;
  v_template_version integer;
  v_schema_version integer;
  v_scope_ids jsonb;
  v_schedule_version_id bigint;
  v_snapshot_id bigint;
  v_payload text;
BEGIN
  SELECT p.template_id, t.version, NULLIF(t.data->>'schemaVersion', '')::integer
    INTO v_template_id, v_template_version, v_schema_version
  FROM public.projects p LEFT JOIN public.templates t ON t.id = p.template_id
  WHERE p.id = NEW.project_id;

  SELECT COALESCE(jsonb_agg(wp_id ORDER BY wp_id), '[]'::jsonb)
    INTO v_scope_ids
  FROM public.project_gantt_tasks
  WHERE project_id = NEW.project_id AND NOT COALESCE(is_archived, false);

  IF v_scope_ids = '[]'::jsonb THEN
    SELECT COALESCE(p.scope->'workPackages', '[]'::jsonb) INTO v_scope_ids
    FROM public.projects p WHERE p.id = NEW.project_id;
  END IF;

  -- Schedule provenance remains null until R1.2 proves a report-period-safe
  -- schedule selection rule; no mutable schedule is silently claimed here.
  v_schedule_version_id := NULL;
  v_payload := concat_ws('|', 'r1', COALESCE(v_template_id::text, ''), COALESCE(v_template_version::text, ''),
    COALESCE(v_schema_version::text, ''), array_to_string(ARRAY(SELECT jsonb_array_elements_text(v_scope_ids) ORDER BY 1), E'\n'),
    NEW.report_date::text, NEW.report_date::text, COALESCE(v_schedule_version_id::text, ''));

  INSERT INTO public.contractor_report_scope_snapshots (
    project_id, template_id, template_version, schema_version, selected_wp_ids,
    scope_fingerprint, report_period_start, report_period_end, schedule_version_id
  ) VALUES (
    NEW.project_id, v_template_id, v_template_version, v_schema_version, v_scope_ids,
    encode(digest(v_payload, 'sha256'), 'hex'), NEW.report_date, NEW.report_date, v_schedule_version_id
  ) RETURNING id INTO v_snapshot_id;

  NEW.scope_snapshot_id := v_snapshot_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS contractor_reports_capture_scope_snapshot ON public.contractor_reports;
CREATE TRIGGER contractor_reports_capture_scope_snapshot
  BEFORE INSERT ON public.contractor_reports
  FOR EACH ROW EXECUTE FUNCTION public.capture_contractor_report_scope_snapshot();

ALTER TABLE public.contractor_report_scope_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.contractor_report_scope_snapshots FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.contractor_report_scope_snapshots TO authenticated;
DROP POLICY IF EXISTS contractor_report_scope_snapshots_select ON public.contractor_report_scope_snapshots;
CREATE POLICY contractor_report_scope_snapshots_select
  ON public.contractor_report_scope_snapshots FOR SELECT TO authenticated
  USING (public.can_access_project(project_id));

REVOKE ALL ON FUNCTION public.capture_contractor_report_scope_snapshot() FROM PUBLIC, anon, authenticated;

-- Preserve the certified atomic submit body as an internal implementation and
-- add evidence fields at its one canonical boundary. This avoids copying the
-- report/progress/Gantt transaction or moving any persistence into React.
DO $$
BEGIN
  IF to_regprocedure('public.submit_contractor_report(bigint,date,jsonb,jsonb)') IS NOT NULL
     AND to_regprocedure('public.submit_contractor_report_r1_base(bigint,date,jsonb,jsonb)') IS NULL THEN
    ALTER FUNCTION public.submit_contractor_report(bigint,date,jsonb,jsonb)
      RENAME TO submit_contractor_report_r1_base;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_contractor_report(
  p_project_id bigint, p_report_date date, p_wp_progress jsonb DEFAULT '[]'::jsonb, p_meta jsonb DEFAULT '{}'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_result jsonb;
  v_report_id bigint;
BEGIN
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(COALESCE(p_wp_progress, '[]'::jsonb))
      AS item("reportItemState" text, "sourceReportWpId" bigint, "confirmationMode" text, "batchConfirmationId" uuid)
    WHERE ("reportItemState" IS NOT NULL AND "reportItemState" NOT IN ('UPDATED','CONFIRMED_UNCHANGED','CARRIED_UNREVIEWED','NOT_IN_REPORTING_SCOPE'))
       OR ("confirmationMode" IS NOT NULL AND "confirmationMode" NOT IN ('INDIVIDUAL','BATCH'))
       OR (("confirmationMode" IS NOT NULL OR "batchConfirmationId" IS NOT NULL) AND "reportItemState" <> 'CONFIRMED_UNCHANGED')
       OR ("sourceReportWpId" IS NOT NULL AND NOT EXISTS (
             SELECT 1 FROM public.contractor_report_wps prior
             WHERE prior.id = "sourceReportWpId" AND prior.project_id = p_project_id))
  ) THEN
    RAISE EXCEPTION 'INVALID_REPORT_ITEM_EVIDENCE_PROVENANCE' USING ERRCODE = '22023';
  END IF;

  v_result := public.submit_contractor_report_r1_base(p_project_id, p_report_date, p_wp_progress, p_meta);
  v_report_id := (v_result->'report'->>'id')::bigint;

  WITH rows AS (
    SELECT * FROM jsonb_to_recordset(COALESCE(p_wp_progress, '[]'::jsonb)) AS x(
      "wpId" text, "reportItemState" text, "sourceReportWpId" bigint,
      "confirmationMode" text, "batchConfirmationId" uuid)
  )
  UPDATE public.contractor_report_wps persisted
  SET report_item_state = rows."reportItemState",
      source_report_wp_id = rows."sourceReportWpId",
      confirmation_mode = rows."confirmationMode",
      batch_confirmation_id = rows."batchConfirmationId"
  FROM rows
  WHERE persisted.report_id = v_report_id AND persisted.wp_id = rows."wpId";

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_contractor_report_r1_base(bigint,date,jsonb,jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.submit_contractor_report(bigint,date,jsonb,jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_contractor_report(bigint,date,jsonb,jsonb) TO authenticated;

COMMIT;
